// The code view: the code toggle's badge, the side pane's tabs, the explorer with git's marks,
// editing and saving a file with its changes in the gutter and its lines' blame, a file changed
// on disk, quick open, find in files, a diff, staging and committing, pushing and pulling, the
// graph, closing an editor tab with ⌘W and the command palette, and the agent's file references,
// in a throwaway repository with a remote of its own. Sends one short message.
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { check, deleteConversations, launch, MODEL, newUserData, shots, waitForReply, waitUntil } from './launch.mjs'

const repo = mkdtempSync(join(tmpdir(), 'kumi-code-repo-'))
const remote = mkdtempSync(join(tmpdir(), 'kumi-code-remote-'))
execFileSync('git', ['init', '-q', '--bare', '-b', 'main', remote])
const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' })
const write = (path, text) => {
  mkdirSync(join(repo, path, '..'), { recursive: true })
  writeFileSync(join(repo, path), text)
}
git('init', '-q', '-b', 'main')
git('config', 'user.email', 'e2e@example.com')
git('config', 'user.name', 'E2E')
// The test's pull runs with an unstaged change, which a rebasing pull refuses.
git('config', 'pull.rebase', 'false')
write('src/math.ts', 'export function add(a: number, b: number): number {\n  return a + b\n}\n')
write('README.md', '# Demo\n')
write('.gitignore', 'dist/\n')
const longText = (changed) => Array.from({ length: 200 }, (_, i) => (i === 149 && changed ? 'line 150, changed' : `line ${i + 1}`)).join('\n') + '\n'
write('long.txt', longText(false))
git('add', '-A')
git('commit', '-qm', 'Initial commit')
git('checkout', '-qb', 'side')
write('src/mul.ts', 'export const mul = (a: number, b: number): number => a * b\n')
git('add', '-A')
git('commit', '-qm', 'Add mul')
git('checkout', '-q', 'main')
git('merge', '-q', '--no-ff', 'side', '-m', 'Merge side')
git('remote', 'add', 'origin', remote)
git('push', '-q', '-u', 'origin', 'main')
// One staged change, one unstaged, one untracked; and an ignored folder.
write('src/index.ts', 'import { add } from "./math"\n\nconsole.log(add(1, 2))\n')
git('add', 'src/index.ts')
write('src/math.ts', 'export function add(a: number, b: number): number {\n  // the sum\n  return a + b\n}\n')
write('notes.txt', 'notes\n')
write('dist/out.js', 'built\n')

const { app, page } = await launch(newUserData())
await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1500, 950))
const state = await page.evaluate(() => window.kumi.getWindowState())
await page.evaluate(([tab, cwd]) => window.kumi.startConversation(tab, cwd), [state.activeTabId, repo])
const view = page.locator('.tab-pane:not([hidden]) .code-view')
// Monaco draws spaces as no-break spaces.
const editorText = async () => (await view.locator('.editor-host:not([hidden]) .view-lines').first().innerText()).replace(/\u00a0/g, ' ')

await page.waitForSelector('.code-badge')
check((await page.locator('.code-badge').innerText()) === '3', 'the code toggle counts staged and unstaged changes, untracked files included')
check((await view.count()) === 0, 'the code view starts closed')
await page.getByRole('button', { name: 'Code', exact: true }).click()
await view.locator('.side-tab.active[title^="Source Control"]').waitFor()
check(true, 'the code view opens on Source Control while there are changes')
check((await view.locator('.side-tab[title^="Source Control"] .side-tab-count').innerText()) === '3', "Source Control's tab counts the changes")
await page.getByRole('button', { name: 'Code', exact: true }).click()

// The explorer, with git's marks.
await page.getByRole('button', { name: 'Code', exact: true }).click()
await view.locator('.side-tab[title^="Explorer"]').click()
await view.locator('.side-tab.active[title^="Explorer"]').waitFor()
await view.locator('.tree-row', { hasText: 'notes.txt' }).waitFor()
check((await view.locator('.tree-row.git-U', { hasText: 'notes.txt' }).count()) === 1, 'an untracked file shows U')
check((await view.locator('.tree-row.ignored', { hasText: 'dist' }).count()) === 1, 'an ignored folder is dimmed')
await view.locator('.tree-row', { hasText: 'src' }).click()
await view.locator('.tree-row', { hasText: 'math.ts' }).click()
await waitUntil(page, 'the file opens', async () => (await editorText()).includes('the sum'))
check((await view.locator('.editor-tab.preview').count()) === 1, 'a click opens the file in a preview tab')

// Editing and saving; a change on disk.
await view.locator('.editor-host:not([hidden]) .view-lines').click()
await page.keyboard.press('Meta+ArrowDown')
await page.keyboard.type('export const ZERO = 0\n')
check((await view.locator('.editor-tab.dirty:not(.preview)').count()) === 1, 'editing marks the tab unsaved and keeps it')
await waitUntil(page, 'the gutter marks the new lines', async () => (await view.locator('.dirty-added').count()) >= 2, 5000)
check(true, 'the gutter marks lines added since the index, unsaved ones included')
await page.keyboard.press('Meta+s')
await waitUntil(page, 'the file is saved', async () => readFileSync(join(repo, 'src/math.ts'), 'utf8').includes('ZERO'), 10000)
check((await view.locator('.editor-tab.dirty').count()) === 0, '⌘S saves the file')

// The cursor's line says who changed it last, and the hover tells more.
const line = (n) => view.locator('.editor-host:not([hidden]) .view-line').nth(n)
const blame = view.locator('.blame-inline')
const blameText = async () => ((await blame.count()) === 1 ? (await blame.innerText()).replace(/\u00a0/g, ' ') : '')
await line(0).click()
await waitUntil(page, "the line's blame shows", async () => (await blameText()).includes('Initial commit'), 10000)
check((await blameText()).startsWith('You, '), `the blame names the commit and says You for the user's own (${await blameText()})`)
await blame.hover()
await page.locator('.monaco-hover', { hasText: 'Initial commit' }).waitFor({ timeout: 5000 })
check((await page.locator('.monaco-hover', { hasText: 'Initial commit' }).innerText()).includes('E2E'), "hovering the blame shows the commit's author and message")
await line(1).click()
await waitUntil(page, 'the uncommitted line says so', async () => (await blameText()).endsWith('Uncommitted changes'), 10000)
check(true, 'a line no commit has is an uncommitted change')
await blame.click()
await page.waitForTimeout(500)
check((await view.locator('.editor-tab.active .editor-tab-title').innerText()) === 'math.ts', 'the blame itself is no link')
const hoverLink = (text) => page.locator('.monaco-hover a', { hasText: text })
await blame.hover()
await hoverLink('Open Changes').click()
await view.locator('.editor-tab.active', { hasText: 'math.ts (Working Tree)' }).waitFor({ timeout: 5000 })
check(true, "an uncommitted line's hover opens the file's changes")
await view.locator('.side-tab.active[title^="Source Control"] ').waitFor({ timeout: 5000 })
check((await view.locator('.scm-row.selected', { hasText: 'math.ts' }).count()) === 1, 'and shows the change in Source Control, highlighted')
const firstCommit = git('rev-list', '--max-parents=0', 'HEAD').trim().slice(0, 7)
await view.locator('.editor-tab-title').getByText('math.ts', { exact: true }).click()
await line(0).click()
await waitUntil(page, "the line's blame shows again", async () => (await blameText()).includes('Initial commit'), 10000)
await blame.hover()
await hoverLink(firstCommit).click()
await view.locator('.editor-tab.active', { hasText: `math.ts (${firstCommit})` }).waitFor({ timeout: 5000 })
check(true, "the hover's commit hash opens the file as that commit changed it")
await view.locator('.graph-file.selected', { hasText: 'math.ts' }).waitFor({ timeout: 5000 })
check((await view.locator('.graph-row.open', { hasText: 'Initial commit' }).count()) === 1 && (await view.locator('.graph-file.selected', { hasText: 'math.ts' }).isVisible()), 'and shows the commit in the graph, opened to the file, highlighted and in sight')
await view.locator('.editor-tab-title').getByText('math.ts', { exact: true }).click()
writeFileSync(join(repo, 'src/math.ts'), 'export const changed = true\n')
await waitUntil(page, 'the editor follows the file', async () => (await editorText()).includes('changed = true'), 10000)
check(true, 'a saved file changed on disk shows the change')

// Quick open and find in files.
await page.locator('.composer textarea').click()
await page.keyboard.press('Meta+p')
await page.keyboard.type('mul')
await view.locator('.quick-item', { hasText: 'mul.ts' }).waitFor()
await page.keyboard.press('Enter')
await waitUntil(page, 'quick open opens the file', async () => (await editorText()).includes('a * b'), 10000)
check((await view.locator('.quick-open').count()) === 0, '⌘P finds a file by name and opens it')
await page.keyboard.press('Meta+Shift+f')
await page.keyboard.type('export')
await view.locator('.search-match').first().waitFor()
check((await view.locator('.search-summary').innerText()) === '2 results in 2 files', `⇧⌘F searches the files' contents (${await view.locator('.search-summary').innerText()})`)
await view.locator('.search-file', { hasText: 'mul.ts' }).waitFor()

// A diff, staging and committing.
await page.keyboard.press('Control+Shift+g')
await view.locator('.scm-row', { hasText: 'notes.txt' }).waitFor()
await view.locator('.scm-row', { hasText: 'index.ts' }).click()
await view.locator('.editor-tab.active', { hasText: 'index.ts (Index)' }).waitFor()
await waitUntil(page, 'the added file shows', async () => (await editorText()).includes('console.log'), 10000)
check((await view.locator('.editor-host:not([hidden]) .monaco-diff-editor').count()) === 0, 'a staged new file opens as its version in the index, not a diff')
await view.locator('.scm-row', { hasText: 'math.ts' }).dblclick()
await view.locator('.editor-tab.active:not(.preview)', { hasText: 'math.ts (Working Tree)' }).waitFor()
await view.locator('.editor-host:not([hidden]) .monaco-diff-editor').waitFor()
check(true, 'an unstaged change opens as a diff of the working tree against the index')
await view.locator('.editor-host:not([hidden]) .modified-in-monaco-diff-editor .view-lines:not(.line-delete) .view-line').first().click()
await waitUntil(page, "the diff's line is blamed", async () => (await blameText()).endsWith('Uncommitted changes'), 10000)
check(true, "a diff's side is blamed as what it shows: here the working tree")

// The row of the tab shown is highlighted, and follows the tabs.
const selectedRows = () => view.locator('.tree-row.selected').allInnerTexts()
check((await selectedRows()).length === 1 && (await selectedRows())[0].startsWith('math.ts'), "the change whose diff shows is highlighted")
await view.locator('.scm-row', { hasText: 'index.ts' }).click()
await view.locator('.editor-tab.active', { hasText: 'index.ts (Index)' }).waitFor()
check((await selectedRows()).length === 1 && (await selectedRows())[0].startsWith('index.ts'), 'opening another change moves the highlight to it')
await view.locator('.editor-tab', { hasText: 'math.ts (Working Tree)' }).click()
await waitUntil(page, 'the highlight follows the tab', async () => (await selectedRows())[0]?.startsWith('math.ts') ?? false, 5000)
check(true, "switching tabs highlights the shown tab's change")
await page.keyboard.press('Meta+Shift+e')
await waitUntil(page, 'the explorer highlights the file', async () => (await selectedRows())[0]?.startsWith('math.ts') ?? false, 5000)
await view.locator('.editor-tab-title').getByText('mul.ts', { exact: true }).click()
await waitUntil(page, 'the explorer follows the tab', async () => (await selectedRows())[0]?.startsWith('mul.ts') ?? false, 5000)
check(true, "the explorer highlights the shown tab's file, and follows the tabs")
await page.keyboard.press('Control+Shift+g')
await view.locator('.scm-row', { hasText: 'notes.txt' }).waitFor()
const notes = view.locator('.scm-row', { hasText: 'notes.txt' })
await notes.hover()
await notes.getByRole('button', { name: 'Stage Changes' }).click()
await waitUntil(page, 'notes.txt is staged', async () => git('status', '--porcelain').includes('A  notes.txt'), 10000)
check(true, 'the row button stages a file')
await view.locator('.commit-box textarea').fill('Commit from the code view')
await view.locator('.commit-box textarea').press('Meta+Enter')
await waitUntil(page, 'the commit exists', async () => git('log', '-1', '--format=%s').trim() === 'Commit from the code view', 10000)
check(git('show', '--name-only', '--format=', 'HEAD').trim().split('\n').sort().join(',') === 'notes.txt,src/index.ts', '⌘Enter commits the staged files')
await waitUntil(page, 'the badge counts what is left', async () => (await page.locator('.code-badge').innerText()) === '1', 10000)
check((await view.locator('.commit-box textarea').inputValue()) === '', 'the message clears after the commit')
await view.locator('.graph-subject', { hasText: 'Commit from the code view' }).waitFor()
check((await view.locator('.graph-row').count()) === 4, 'the graph shows the new commit with the history')

// Pushing and pulling, each a button that says which.
const remoteHead = () => execFileSync('git', ['--git-dir', remote, 'log', '-1', '--format=%s', 'main'], { encoding: 'utf8' }).trim()
await view.locator('.scm-pill[title^="Push 1 commit to origin/main"]').click()
await waitUntil(page, 'the commit is pushed', async () => remoteHead() === 'Commit from the code view', 15000)
await view.locator('.scm-pill').waitFor({ state: 'detached' })
check(true, 'the ↑ button pushes what the branch is ahead by')
// A commit pushed from another clone shows once fetched, and pulls.
const other = mkdtempSync(join(tmpdir(), 'kumi-code-clone-'))
execFileSync('git', ['clone', '-q', remote, other])
const inOther = (...args) => execFileSync('git', ['-c', 'user.email=o@example.com', '-c', 'user.name=Other', ...args], { cwd: other })
writeFileSync(join(other, 'CHANGELOG.md'), 'From elsewhere\n')
inOther('add', '-A')
inOther('commit', '-qm', 'Commit from elsewhere')
inOther('push', '-q')
await page.keyboard.press('Meta+Shift+p')
await page.keyboard.type('git fetch')
await page.keyboard.press('Enter')
await view.locator('.scm-pill[title^="Pull 1 commit from origin/main"]').click()
await waitUntil(page, 'the commit is pulled', async () => git('log', '-1', '--format=%s').trim() === 'Commit from elsewhere', 15000)
check(readFileSync(join(repo, 'CHANGELOG.md'), 'utf8') === 'From elsewhere\n', 'Git: Fetch finds a commit to pull, and the ↓ button pulls it')
await view.locator('.graph-row', { hasText: 'Add mul' }).click()
await view.locator('.graph-file', { hasText: 'mul.ts' }).waitFor()
check(true, "a commit in the graph opens to the files it changed")
await view.locator('.graph-file', { hasText: 'mul.ts' }).click()
await view.locator('.editor-tab.active', { hasText: 'mul.ts (' }).waitFor()
check((await view.locator('.graph-file.selected', { hasText: 'mul.ts' }).count()) === 1, "the commit's file whose change shows is highlighted")
await line(0).click()
await waitUntil(page, "the commit's version is blamed", async () => (await blameText()).includes('Add mul'), 10000)
check(true, "a commit's version of a file is blamed as of that commit")
await page.screenshot({ path: `${shots}/code.png` })

// A diff opened for the first time shows its first change.
writeFileSync(join(repo, 'long.txt'), longText(true))
await page.keyboard.press('Control+Shift+g')
await view.locator('.scm-row', { hasText: 'long.txt' }).click()
await view.locator('.editor-tab.active', { hasText: 'long.txt (Working Tree)' }).waitFor()
await waitUntil(page, 'the diff scrolls to its change', async () => (await view.locator('.editor-position').innerText()).startsWith('Ln 150,'), 10000)
check((await view.locator('.editor-host:not([hidden]) .modified-in-monaco-diff-editor .view-line', { hasText: 'line 150, changed' }).count()) === 1, 'a diff opens at its first change')
const position = () => view.locator('.editor-position').innerText()
const toTop = async () => {
  // A line in sight: Monaco keeps the first one it draws above the view.
  await view.locator('.editor-host:not([hidden]) .modified-in-monaco-diff-editor .view-lines:not(.line-delete) .view-line', { hasText: 'line 150, changed' }).click()
  await page.keyboard.press('Meta+ArrowUp')
  await waitUntil(page, 'the cursor is at the top', async () => (await position()).startsWith('Ln 1,'), 5000)
}
const longRow = view.locator('.scm-row', { hasText: 'long.txt' })
const atChange = () => waitUntil(page, 'the diff shows its change', async () => (await position()).startsWith('Ln 150,'), 10000)
await toTop()
await longRow.click()
await atChange()
check(true, 'opening a change again shows its first change again')
await toTop()
await page.keyboard.press('Meta+w')
await view.locator('.editor-tab', { hasText: 'long.txt' }).waitFor({ state: 'detached' })
await longRow.click()
await atChange()
check(true, 'a closed diff opened again shows its first change')
await view.locator('.scm-row', { hasText: 'math.ts' }).click()
await view.locator('.editor-tab.active', { hasText: 'math.ts (Working Tree)' }).waitFor()
await longRow.click()
await atChange()
check(true, 'a diff whose preview tab another change took shows its first change when opened again')
await longRow.dblclick()
await toTop()
await view.locator('.editor-tab', { hasText: 'math.ts (Working Tree)' }).click()
await view.locator('.editor-tab', { hasText: 'long.txt (Working Tree)' }).click()
await page.waitForTimeout(500)
check((await position()).startsWith('Ln 1,'), 'switching back to a diff tab finds it where it was left')

// ⌘W closes the editor's tab, not the conversation's; the command palette.
const tabs = await view.locator('.editor-tab').count()
// The editor shown: a file's, or a diff's right side.
await view.locator('.editor-host:not([hidden]) .view-lines:not(.line-delete)').last().click()
await page.keyboard.press('Meta+w')
await waitUntil(page, 'an editor tab closes', async () => (await view.locator('.editor-tab').count()) === tabs - 1, 5000)
check((await page.evaluate(() => window.kumi.getWindowState())).tabs.length === 1, '⌘W in the editor closes its tab and leaves the conversation open')
await page.keyboard.press('Meta+Shift+p')
await page.keyboard.type('stage all')
check((await view.locator('.quick-item').first().innerText()).startsWith('Git: Stage All Changes'), '⇧⌘P lists commands')
await page.keyboard.press('Escape')

// The agent's references to files open them in the code view: a markdown link, and a path in inline code.
const conversationId = (await page.evaluate(() => window.kumi.getWindowState())).tabs[0].conversationId
await page.waitForFunction((model) => [...(document.querySelectorAll('.composer-bar select')[1]?.options ?? [])].some((o) => o.value === model), MODEL, { timeout: 60000 })
await page.evaluate(([id, model]) => window.kumi.setModel(id, model), [conversationId, MODEL])
await page.locator('.composer textarea').fill('Reply with exactly this line and nothing else, keeping its markdown: See [the sum](src/math.ts:1) and `src/mul.ts`.')
await page.keyboard.press('Enter')
await waitForReply(page, 1)
await page.locator('.item.text a.file-link').click()
await view.locator('.editor-tab.active .editor-tab-title', { hasText: /^math\.ts$/ }).waitFor({ timeout: 5000 })
check(true, "a markdown link to a file in the agent's reply opens it in the code view")
await page.locator('.item.text code.file-ref', { hasText: 'src/mul.ts' }).click()
await view.locator('.editor-tab.active .editor-tab-title', { hasText: /^mul\.ts$/ }).waitFor({ timeout: 5000 })
check(true, "a file's path in inline code opens it too")

await deleteConversations(page)
await app.close()
